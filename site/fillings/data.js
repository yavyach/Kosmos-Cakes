/* Сортирует произвольный список имён начинок по KOSMOS_FILLINGS_ORDER.
   Имена, отсутствующие в порядке, уходят в конец в исходной очерёдности. */
window.sortByCanonical = function(list){
  const order = window.KOSMOS_FILLINGS_ORDER || [];
  const idx = name => {
    const i = order.indexOf(name);
    return i === -1 ? 1e9 : i;
  };
  return list.slice().sort((a,b) => idx(a) - idx(b));
};

